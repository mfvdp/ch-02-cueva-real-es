    // Marca para volver a jugar tras el fin de la partida. La pantalla final la pone justo antes de control.reset(). En
    // el arranque siguiente el juego la lee, la borra enseguida y va directo a la imagen del título, sin intro. Si se
    // apaga y se enciende la consola, la marca ya no está y la intro se ve otra vez.
    export const marcaReinicio = "neustart-titel"
    // Es verdadero cuando este arranque es un nuevo comienzo después del fin de la partida.
    export let directoAlTitulo = false
    export function texto(id: IdTexto): string {
        return textos[id]
    }
    export function formatear(id: IdTexto, primero: number, segundo: number = 0): string {
        let resultado = texto(id)
        let posicion = resultado.indexOf("{0}")
        if (posicion >= 0) resultado = resultado.substr(0, posicion) + primero + resultado.substr(posicion + 3)
        posicion = resultado.indexOf("{1}")
        if (posicion >= 0) resultado = resultado.substr(0, posicion) + segundo + resultado.substr(posicion + 3)
        return resultado
    }
    // Al arrancar: si la marca de reinicio está puesta, el juego va directo a la imagen del título. La marca vale solo
    // para este arranque y se borra enseguida. Después se añade el menú de pausa.
    export function inicializar(): void {
        directoAlTitulo = settings.exists(marcaReinicio)
        if (directoAlTitulo) settings.remove(marcaReinicio)
        pause(100)
        instalarMenus()
    }
